"""Generate approximate preview colors from manufacturer door-panel photos.

Requires ImageMagick. Does not modify catalog records, photos, or pricing.
"""
import json, subprocess
from pathlib import Path

root = Path(__file__).resolve().parents[1]
samples, cache = {}, {}
crop = [0.38, 0.50, 0.62, 0.72]
for file in sorted((root / 'dist/private-catalogs/fabuwood').glob('*.json')):
    catalog = json.loads(file.read_text())
    if not isinstance(catalog, dict):
        continue
    for finish in catalog.get('finishes', []):
        if any(name in finish.get('name', '').lower() for name in ['benjamin moore', 'sherwin williams', 'custom']):
            continue
        image = (finish.get('imageUrl') or '').lstrip('/')
        if finish.get('textureUrl') or finish.get('baseColorFactor') or not image:
            continue
        if not image.startswith('assets/private-catalogs/') or '..' in image:
            continue
        path = root / 'dist' / image
        if path.name not in cache:
            w, h = map(int, subprocess.check_output(['magick', str(path), '-format', '%w %h', 'info:'], text=True).split())
            geometry = f'{round(w*.24)}x{round(h*.22)}+{round(w*.38)}+{round(h*.50)}'
            srgb = list(map(float, subprocess.check_output(['magick', str(path), '-crop', geometry, '+repage', '-format', '%[fx:mean.r] %[fx:mean.g] %[fx:mean.b]', 'info:'], text=True).split()))
            linear = [round(v/12.92 if v <= .04045 else ((v+.055)/1.055)**2.4, 7) for v in srgb]
            cache[path.name] = {'baseColorFactor': linear, 'approximateFinish': True, 'sourceImage': image, 'crop': crop}
        samples[image] = {**cache[path.name], 'sourceImage': image}
output = root / 'dist/catalog-finish-samples.js'
output.write_text('// Approximate sRGB photo samples converted to linear RGB. Generated by scripts/sample-finish-colors.py.\nexport const FINISH_SAMPLES = ' + json.dumps(samples, separators=(',', ':')) + ';\n')
print(f'Generated {len(samples)} finish previews from {len(cache)} unique manufacturer images.')
