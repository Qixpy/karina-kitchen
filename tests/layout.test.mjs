import assert from 'node:assert/strict';
import * as THREE from '../dist/vendor/three.module.js';
import {createRoom} from '../dist/room.js';
import {isWalkable} from '../dist/collision.js';
THREE.TextureLoader.prototype.loadAsync=async()=>new THREE.Texture();
const scene=new THREE.Scene(),room=await createRoom(THREE,scene);
assert.equal(room.wallSegments.length,3,'three faceted walls');
assert.equal(room.colliders.filter(c=>c.kind==='stool').length,4,'four island seats');
assert.equal(room.colliders.filter(c=>c.kind==='oven').length,1,'one double-oven tower');
assert.ok(room.cabinetFacing.oven.x>.45&&room.cabinetFacing.oven.z>.8,'oven faces inward from left wing');
assert.ok(room.cabinetFacing.right.x<-.45&&room.cabinetFacing.right.z>.8,'right run faces inward');
assert.equal(room.cabinetFacing.stove.x,0,'stove faces straight into the room');
assert.ok(room.island.width>=3.8,'restore spacious island proportions');
const dx=room.island.sink.x-room.island.x,dz=room.island.sink.z-room.island.z,a=room.island.rotation;
const sx=Math.cos(a)*dx-Math.sin(a)*dz,sz=Math.sin(a)*dx+Math.cos(a)*dz;
assert.ok(Math.abs(sx)<room.island.width/2&&sz<0&&Math.abs(sz)<room.island.depth/2,'sink lies on island working side');
assert.ok(isWalkable(.35,.25,room.colliders,room.bounds),'cooking viewpoint stays in the aisle');
assert.ok(isWalkable(2.4,3.85,room.colliders,room.bounds),'walking start clears stools');
let meshes=0;scene.traverse(o=>{if(o.isMesh){meshes++;o.geometry.computeBoundingBox();const b=o.geometry.boundingBox;assert.ok([...b.min.toArray(),...b.max.toArray()].every(Number.isFinite),'finite geometry')}});
console.log(`Layout checks passed: 3 wall facets, 4 stools, island sink, inward cabinet faces, ${meshes} valid meshes.`);
